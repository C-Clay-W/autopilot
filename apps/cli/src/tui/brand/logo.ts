/** 按字符网格采样原图，每个 Braille 字符承载 2×4 个点。 */
export function createAgentLogoRows(width: number, height: number): string[] {
  const rows: string[] = [];
  const bits = [[0, 3], [1, 4], [2, 5], [6, 7]];
  for (let row = 0; row < height; row += 1) {
    let line = "";
    for (let column = 0; column < width; column += 1) {
      let dots = 0;
      for (let y = 0; y < 4; y += 1) {
        for (let x = 0; x < 2; x += 1) {
          const sourceY = Math.min(63, Math.floor((row * 4 + y + 0.5) * 64 / (height * 4)));
          const sourceX = Math.min(63, Math.floor((column * 2 + x + 0.5) * 64 / (width * 2)));
          if (LOGO_MASK[sourceY]?.[sourceX] === "1") dots |= 1 << bits[y]![x]!;
        }
      }
      line += dots ? String.fromCharCode(0x2800 + dots) : " ";
    }
    rows.push(line);
  }
  return rows;
}
